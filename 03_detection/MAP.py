#NMS 解决的是：预测框太多、重复。
# MAP:这些框到底预测得准不准？
import numpy as np


# ============================================================
# 1. IoU
def compute_iou(box1, box2):
    # 交集左上角
    x1 = max(box1[0], box2[0])
    y1 = max(box1[1], box2[1])
    # 交集右下角
    x2 = min(box1[2], box2[2])
    y2 = min(box1[3], box2[3])
    # 交集宽度
    inter_width = max(0, x2 - x1)
    # 交集高度
    inter_height = max(0, y2 - y1)
    # 交集面积
    inter_area = inter_width * inter_height
    # box1 面积
    area1 = (
        (box1[2] - box1[0])
        *
        (box1[3] - box1[1])
    )
    # box2 面积
    area2 = (
        (box2[2] - box2[0])
        *
        (box2[3] - box2[1])
    )
    # 并集面积
    union_area = area1 + area2 - inter_area
    # IoU
    if union_area > 0:
        return inter_area / union_area
    else:
        return 0

# ============================================================
# 2. AP
def compute_ap(
    pred_boxes,
    pred_scores,
    gt_boxes,
    iou_threshold=0.5
):
# 第一步：按照置信度从高到低排序
    # 假设：pred_scores =
    # [0.95, 0.80, 0.60]
    # 排序以后：
    # 0.95
    # 0.80
    # 0.60
    #
    # 后面我们就按照这个顺序判断：
    # 第一个预测对不对？
    # 第二个预测对不对？
    # 第三个预测对不对？
    order = np.argsort(
        pred_scores
    )[::-1]
    # 根据排序结果重新排列预测框
    # ========================================================
    pred_boxes = [
        pred_boxes[i]
        for i in order
    ]

    # ========================================================
    # 同样重新排列预测置信度
    # ========================================================

    pred_scores = [
        pred_scores[i]
        for i in order
    ]


    # ========================================================
    # TP / FP
    #
    # 例如：
    #
    # TP = [1, 1, 0, 1]
    #
    # 表示：
    #
    # 第1个预测：正确
    # 第2个预测：正确
    # 第3个预测：错误
    # 第4个预测：正确
    #
    # ========================================================

    tp = []
    fp = []


    # ========================================================
    # 保存已经被匹配过的 GT
    #
    # 非常重要！
    #
    # 一个 GT 只能被一个预测框匹配。
    #
    # ========================================================

    matched_gt = set()


    # ========================================================
    # 开始遍历预测框
    # ========================================================

    for pred in pred_boxes:


        # ----------------------------------------------------
        # 当前预测框与 GT 的最高 IoU
        # ----------------------------------------------------

        best_iou = 0


        # ----------------------------------------------------
        # 最匹配的 GT 编号
        #
        # -1 表示目前没有找到匹配
        # ----------------------------------------------------

        best_gt_idx = -1


        # ====================================================
        # 把当前预测框和所有 GT 比较
        # ====================================================

        for idx, gt in enumerate(gt_boxes):


            # ------------------------------------------------
            # 如果这个 GT 已经被其他预测框匹配了
            # 就不能再次匹配
            # ------------------------------------------------

            if idx in matched_gt:

                continue


            # ------------------------------------------------
            # 计算 IoU
            # ------------------------------------------------

            iou = compute_iou(
                pred,
                gt
            )
            # 如果当前 IoU 比之前最高 IoU 更大
            # 就更新
            # ------------------------------------------------

            if iou > best_iou:

                best_iou = iou

                best_gt_idx = idx


        # ====================================================
        # 判断当前预测到底是 TP 还是 FP
        # ====================================================

        if best_iou >= iou_threshold:

            # ------------------------------------------------
            # IoU 达到要求
            #
            # 说明预测框成功匹配一个真实目标
            # ------------------------------------------------

            tp.append(1)

            fp.append(0)


            # ------------------------------------------------
            # 把这个 GT 标记为“已经匹配”
            # ------------------------------------------------

            matched_gt.add(
                best_gt_idx
            )


        else:

            # ------------------------------------------------
            # IoU 不够
            #
            # 说明预测失败
            # ------------------------------------------------

            tp.append(0)

            fp.append(1)


    # ========================================================
    # TP 累积数量
    # ========================================================
    # tp =
    #
    # [1, 1, 0, 1]
    # 那么：
    # tp_cum =[1, 2, 2, 3]
    #
    # ========================================================

    tp_cum = np.cumsum(tp)


    # ========================================================
    # FP 累积数量
    fp_cum = np.cumsum(fp)

    # Precision =
    #
    # TP / (TP + FP)
    #
    # “预测出来的东西，有多少是真的？”
    # ========================================================

    precision = (
        tp_cum
        /
        (tp_cum + fp_cum + 1e-10)
    )

    # Recall =
    #
    # TP / GT总数量
    #
    # “所有真实目标，我找到了多少？”
    # ========================================================

    recall = (
        tp_cum
        /
        (len(gt_boxes) + 1e-10)
    )


    # ========================================================
    # 打印中间结果
    # ========================================================

    print("\n==============================")
    print("预测框排序后的结果")
    print("==============================")

    print("TP：", tp)
    print("FP：", fp)

    print("累计 TP：", tp_cum)
    print("累计 FP：", fp_cum)

    print("Precision：", precision)
    print("Recall：", recall)


    # ========================================================
    # 计算 AP
    # ========================================================

    ap = 0

    # 上一次的 Recall
    prev_recall = 0


    # ========================================================
    # 按照 Recall 从小到大计算 PR 曲线面积
    # ========================================================

    for p, r in zip(
        precision,
        recall
    ):

        # ----------------------------------------------------
        # 当前这一小段面积
        #
        # 宽：
        #
        # r - prev_recall
        #
        # 高：
        #
        # p
        #
        # 面积：
        #
        # p × (r - prev_recall)
        # ----------------------------------------------------

        ap += (
            p *
            (r - prev_recall)
        )


        # 更新上一轮 Recall
        prev_recall = r
    # 返回 AP
    # ========================================================

    return ap


# ============================================================
# 3. 准备真实框 GT
# ============================================================

gt_boxes = np.array([

    # GT 0
    [100, 100, 200, 200],

    # GT 1
    [300, 300, 400, 400],

])


# ============================================================
# 4. 准备预测框
# ============================================================

pred_boxes = np.array([

    # Prediction 0
    # 和 GT0 高度重叠
    [105, 105, 195, 195],


    # Prediction 1
    # 和 GT1 高度重叠
    [305, 305, 395, 395],


    # Prediction 2
    # 一个错误预测
    [500, 500, 600, 600],

])


# ============================================================
# 5. 预测置信度
# ============================================================

pred_scores = np.array([

    0.95,
    0.80,
    0.60

])


# ============================================================
# 6. 计算 AP
# ============================================================

ap = compute_ap(
    pred_boxes,
    pred_scores,
    gt_boxes,
    iou_threshold=0.5
)


# ============================================================
# 7. 输出 AP
# ============================================================

print("\n==============================")
print("最终结果")
print("==============================")

print(
    f"AP@0.5 = {ap:.4f}"
)