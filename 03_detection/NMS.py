import numpy as np
# ============================================================
# 1. 计算两个矩形框之间的 IoU
# box 的格式：
# [x1, y1, x2, y2]
# 其中：
# x1 = 左上角 x
# y1 = 左上角 y
# x2 = 右下角 x
# y2 = 右下角 y
def compute_iou(box1, box2):
# 第一步：计算两个框“相交区域”的左上角
    # 左边界取两个框左边界中较大的那个
    x1 = max(box1[0], box2[0])
    # 上边界取两个框上边界中较大的那个
    y1 = max(box1[1], box2[1])
 # 第二步：计算两个框“相交区域”的右下角
    x2 = min(box1[2], box2[2])
    # 下边界取两个框下边界中较小的那个
    y2 = min(box1[3], box2[3])
# 第三步：计算交集面积
    # x2 - x1 可能 < 0
    # y2 - y1 可能 < 0
    # 所以用 max(0, ...)这样没有交集的时候：inter = 0

    inter_width = max(0, x2 - x1)
    inter_height = max(0, y2 - y1)
    inter = inter_width * inter_height
 # 第四步：计算 box1 面积
    area1 = (
        (box1[2] - box1[0])
        *
        (box1[3] - box1[1])
    )
# 第五步：计算 box2 面积
    area2 = (
        (box2[2] - box2[0])
        *
        (box2[3] - box2[1])
    )
 # 第六步：计算并集面积
    # union = area1 + area2 - inter
    union = area1 + area2 - inter
# 第七步：计算 IoU
    # IoU = 交集面积 / 并集面积
    if union > 0:
        return inter / union
    else:
        return 0

# ============================================================
# 2. NMS：Non-Maximum Suppression
#    非极大值抑制：“按照置信度从高到低，留下最可信的框，然后把和它高度重叠的框删掉，再继续。”
# 输入：boxes：所有预测框
# scores：每个预测框的置信度
# iou_threshold：IoU 阈值

# 输出：最终保留的预测框索引
def nms(boxes, scores, iou_threshold=0.5):
# 第一步：
    # 按照置信度从高到低排列假设：scores =
    # [0.90, 0.75, 0.85]
    # 对应：
    # box0 = 0.90
    # box1 = 0.75
    # box2 = 0.85

    # np.argsort(scores)
    # 得到：
    # [1, 2, 0]因为： 0.75 < 0.85 < 0.90
    # [::-1]把它反过来： 所以：order = [0, 2, 1]
    # 表示：第一优先处理 box0
    # 第二处理 box2
    # 第三处理 box1
    order = np.argsort(scores)[::-1]
    keep = []# 用来保存最终留下来的框

    # ========================================================
    # 开始循环
    while len(order) > 0:
        # 当前置信度最高的框
        # ----------------------------------------------------
        # 例如：
        # order = [0, 2, 1]
        # 那么：
        # i = 0

        i = order[0]
        # ----------------------------------------------------
        # 当前这个框直接保留
        # 因为它是当前剩余框中置信度最高的
        keep.append(i)


        # ----------------------------------------------------
        # 计算当前框和其他框的 IoU
        #
        # order[1:]
        #
        # 表示除了当前框之外的其他框
        #
        # 例如：
        #
        # order = [0, 2, 1]
        #
        # order[1:] = [2, 1]
        #
        # 所以现在计算：
        #
        # IoU(box0, box2)
        # IoU(box0, box1)
        # ----------------------------------------------------

        ious = np.array([
            compute_iou(boxes[i], boxes[j])
            for j in order[1:]
        ])


        # ----------------------------------------------------
        # 找到 IoU 小于阈值的框
        #
        # 例如：
        #
        # ious = [0.00, 0.68]
        #
        # threshold = 0.5
        #
        # 那么：
        #
        # [0.00 < 0.5, 0.68 < 0.5]
        #
        # 得：
        #
        # [True, False]
        #
        # True：
        #       说明这个框和当前框不太重叠
        #       可以继续保留
        #
        # False：
        #       说明这个框和当前框高度重叠
        #       删除
        #
        # ----------------------------------------------------

        remaining = np.where(
            ious < iou_threshold
        )[0]


        # ----------------------------------------------------
        # 更新 order order[1:] 是：[2, 1]
        # remaining 可能是： [0]
        # 那么：
        #
        # order[remaining + 1]= order[[1]]
        #
        # = [2]
        #
        # 意思：
        #
        # box1 被删除
        # box2 保留
        #
        # 下一轮：
        #
        # order = [2]
        #
        # ----------------------------------------------------

        order = order[remaining + 1]

    # 返回最终保留的框
    # --------------------------------------------------------
    return keep


# ============================================================
# 3. 测试 NMS
# ============================================================

boxes = np.array([

    # Box A
    [100, 100, 200, 200],

    # Box B
    # 和 A 高度重叠
    [105, 105, 205, 205],

    # Box C
    # 和 A、B 都基本不重叠
    [300, 300, 400, 400],
])

# 每个框的置信度
scores = np.array([

    0.90,   # A
    0.75,   # B
    0.85    # C

])

# ============================================================
# 4. 执行 NMS
# ============================================================

keep = nms(
    boxes,
    scores,
    iou_threshold=0.5
)

# ============================================================
# 5. 输出结果
# ============================================================
print("最终保留的框索引：", keep)

for i in keep:

    print(
        "框：",
        boxes[i],
        "置信度：",
        scores[i]
    )